import UserProgressCard from "@/components/Progress/UserProgressCard";
import axios from "axios";
import Head from "next/head";
import Link from "next/link";
import { useRouter } from "next/router";
import React, { useEffect, useState } from "react";

export default function AllProgressPage() {
  const [data, setData] = useState({ users: [], tasks: [] });

  const router = useRouter();

  useEffect(() => {
    async function getData() {
      const tasks = await axios.get("/api/task");

      let users = [];

      const email = router.query.email;

      if (email) {
        users = await axios.get(`/api/user/?email=${email}`);

        console.log(users.data);
      } else {
        users = await axios.get(`/api/user`);
      }

      setData({
        users: users.data,
        tasks: tasks.data,
      });
    }

    getData();
  }, [router.query]);

  return (
    <div className="p-4 space-y-2">
      <Head>
        <title>Progress Tracker</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      {router.query.email && (
        <div className="pb-4 flex justify-end w-full">
          <Link href="/all-progress">
            <span className="bg-white py-1 px-4 rounded-full cursor-pointer">
              Clear
            </span>
          </Link>
        </div>
      )}

      {data.users.length === 0 && (
        <h1 className="text-white text-xl font-bold text-center">No Users</h1>
      )}

      {data.users.map((user) => {
        return (
          <UserProgressCard
            key={user._id}
            taskCount={data.tasks.length}
            {...user}
          />
        );
      })}
    </div>
  );
}
